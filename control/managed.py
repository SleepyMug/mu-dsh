"""What mu-dsh contributes to every user's dsh, in three layers:

* the ``mu-dsh-defaults`` bundle: the model provider and default model.
  Bundles sit below the user's profile patch, so a user may change these in
  dsh's settings like any shipped default.
* the home-level patch ``~/.dsh/cordis.patch.yml``: telemetry and web search
  off. dsh applies it over every profile and refuses settings edits it
  would override.
* a marked block at the top of ``~/.dsh/.env``: the user's relay key and the
  ``[dsh.env]`` variables dsh accepts there; lines below it override them.
"""

from __future__ import annotations

import json
import re

from control.config import Config

PATCH_MARKER = "# Managed by mu-dsh"
DEFAULTS_BUNDLE = "mu-dsh-defaults"
BASE_BUNDLE = "@deepseek-ai/dsh-base"  # every profile built on it gets the defaults bundle
PROFILE = "web"  # what the gateway serves
PROFILES = ("web", "headless")  # created up front, so `dsh headless` in a shell has the defaults too
# Recovery mode runs this profile instead of PROFILE: rebuilt from dsh's shipped
# web template on every recovery start, so none of the user's settings or
# plugins load; sessions and credentials live outside profiles and stay.
RECOVERY_PROFILE = "mu-dsh-recovery"
ENV_BEGIN = "# >>> mu-dsh managed >>>"
ENV_END = "# <<< mu-dsh managed <<<"
LLM_KEY_ENV = "MUDSH_LLM_KEY"

_PLAIN_KEY = re.compile(r"[A-Za-z_][A-Za-z0-9_.-]*")


def _scalar(value: object) -> str:
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)  # a JSON string is a valid YAML double-quoted scalar
    raise TypeError(f"cannot emit {type(value).__name__} as YAML")


# Plain scalars YAML 1.1 parsers read as booleans or null (an effort level is named "off").
_AMBIGUOUS = {"y", "n", "yes", "no", "on", "off", "true", "false", "null", "~"}


def _key(key: str) -> str:
    plain = _PLAIN_KEY.fullmatch(key) and key.lower() not in _AMBIGUOUS
    return key if plain else json.dumps(key, ensure_ascii=False)


def _emit(value: object, indent: int) -> list[str]:
    pad = "  " * indent
    if isinstance(value, dict):
        if not value:
            return [pad + "{}"]
        lines = []
        for k, v in value.items():
            if isinstance(v, (dict, list)) and v:
                lines.append(f"{pad}{_key(k)}:")
                lines += _emit(v, indent + 1)
            elif isinstance(v, (dict, list)):
                lines.append(f"{pad}{_key(k)}: {'{}' if isinstance(v, dict) else '[]'}")
            else:
                lines.append(f"{pad}{_key(k)}: {_scalar(v)}")
        return lines
    if isinstance(value, list):
        if not value:
            return [pad + "[]"]
        lines = []
        for item in value:
            sub = _emit(item, indent + 1)
            lines.append(f"{pad}- {sub[0].lstrip()}")
            lines += sub[1:]
        return lines
    return [pad + _scalar(value)]


def to_yaml(value: object) -> str:
    return "\n".join(_emit(value, 0)) + "\n"


def defaults_entries(config: Config) -> list[dict]:
    llm = config.llm
    provider: dict = {
        "displayName": llm.display_name,
        "api": llm.api,
        "baseURL": config.relay.base_url,
        "apiKeyEnv": LLM_KEY_ENV,
        "models": [dict(m) for m in llm.models],
    }
    if llm.compat:
        provider["compat"] = llm.compat
    return [
        {"id": "llm-pi-ai", "config": {"providers": {llm.provider_id: provider}}},
        {"id": "agent-default-model", "config": {"provider": llm.provider_id, "model": llm.default_model}},
    ]


def policy_entries() -> list[dict]:
    return [
        # Web search goes to DeepSeek's official API with DEEPSEEK_API_KEY; not available on-prem.
        {"id": "web-search-deepseek", "disabled": True},
        {"id": "web-deepseek-api", "disabled": True},
        {"id": "session-telemetry-otel", "config": {"mode": "DISABLED"}},
    ]


def defaults_text(config: Config) -> str:
    header = (
        "# mu-dsh defaults for every user, from /etc/mu-dsh/config.toml; rewritten on\n"
        "# every reload. A user's own profile patch overrides these rows.\n"
    )
    return header + to_yaml(defaults_entries(config))


def policy_text() -> str:
    header = (
        f"{PATCH_MARKER}; this file is rewritten whenever your dsh starts.\n"
        "# Site policy for every profile. Put your own changes in\n"
        "# ~/.dsh/profiles/<profile>/cordis.patch.yml; the model provider and\n"
        "# default model can be changed there or in dsh's settings.\n"
    )
    return header + to_yaml(policy_entries())


def bundle_manifest() -> str:
    manifest = {
        "name": DEFAULTS_BUNDLE,
        "version": "0.0.0",
        "private": True,
        "description": "Generated by mu-dsh: site defaults for every user's dsh",
        "dsh": {"bundle": {"patch": "cordis.patch.yml"}},
    }
    return json.dumps(manifest, indent=2) + "\n"


def env_line(name: str, value: str) -> str:
    return f"{name}='{value}'"  # single quotes: no expansion; config.py refuses ' in these values


def env_block(llm_key: str, file_env: tuple[tuple[str, str], ...] = ()) -> str:
    lines = [ENV_BEGIN, "# Set by mu-dsh; lines below this block override it.", f"{LLM_KEY_ENV}={llm_key}"]
    lines += [env_line(k, v) for k, v in file_env]
    return "\n".join(lines + [ENV_END]) + "\n"
